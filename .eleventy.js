module.exports = function (eleventyConfig) {
  // ── Passthrough: copy assets unchanged ─────────────────────────
  eleventyConfig.addPassthroughCopy("src/assets");
  eleventyConfig.addPassthroughCopy({ "src/CNAME": "CNAME" });

  // UNC Viet materials: course pages are built from templates, but static
  // files dropped alongside them (PDFs, slides, audio, images) pass through
  // untouched — no templating.
  eleventyConfig.addPassthroughCopy("src/uncviet/**/*.pdf");
  eleventyConfig.addPassthroughCopy("src/uncviet/**/*.{png,jpg,jpeg,gif,svg,webp,avif}");
  eleventyConfig.addPassthroughCopy("src/uncviet/**/*.{mp3,mp4,wav,webm}");
  eleventyConfig.addPassthroughCopy("src/uncviet/**/*.{docx,pptx,xlsx}");

  // VIET 101 homework — its own copy of the VIET 100 engine (assets/) + per-page data
  eleventyConfig.addPassthroughCopy("src/uncviet/viet101/viet101-hw/data");
  eleventyConfig.addPassthroughCopy("src/uncviet/viet101/viet101-hw/assets");
  eleventyConfig.addPassthroughCopy("src/uncviet/viet203/data");
  eleventyConfig.addPassthroughCopy("src/uncviet/viet203/assets");  // VIET 203 task guides' own copy of the engine (from viet101-hw)

  // UC San Diego course audio
  eleventyConfig.addPassthroughCopy("src/ucsd/**/*.{mp3,mp4,wav,webm}");
  // Quiz source files contain answer keys — never publish
  eleventyConfig.ignores.add("src/ucsd/**/*.md");
  // Instructor recorder — a plain page + generated items.js, copied as-is (not a template); unlisted, noindex
  eleventyConfig.addPassthroughCopy("src/ucsd/recorder");
  eleventyConfig.ignores.add("src/ucsd/recorder/**");

  // Yale Vietnamese logo page — static images pass through untouched
  eleventyConfig.addPassthroughCopy("src/yale/**/*.{png,jpg,jpeg,gif,svg,webp,avif}");

  // UniVE program — Vietnamese Vibes interactive books (hosted on Netlify,
  // framed by pages here); only the shared stylesheet/images pass through
  eleventyConfig.addPassthroughCopy("src/unive/**/*.{css,png,jpg,jpeg,svg,webp}");
  // Self-hosted copies of the books: plain single-file apps, copied byte for
  // byte (never run through Nunjucks — their JS uses ${...} templates)
  eleventyConfig.addPassthroughCopy("src/unive/books");
  eleventyConfig.ignores.add("src/unive/books/**");

  // Taskbook — standalone single-file task pages (generated by
  // _tools/taskbook/) plus their images, copied byte for byte. Never run
  // through templating; the md sources live in _source/taskbook/.
  eleventyConfig.addPassthroughCopy("src/taskbook/*.html");
  eleventyConfig.addPassthroughCopy("src/taskbook/img");
  eleventyConfig.ignores.add("src/taskbook/**");

  // ── Ignore draft and source folders entirely ────────────────────
  eleventyConfig.ignores.add("_drafts/**");
  eleventyConfig.ignores.add("_source/**");

  // ── Sections not yet ready for public launch ─────────────────────
  // Source stays in the repo (and still builds locally with `--input=src`
  // overrides if needed) — these are just excluded from the deployed site.
  eleventyConfig.ignores.add("src/read/**");
  eleventyConfig.ignores.add("src/exam/**");

  // Local working docs that live next to the thing they document — never
  // published (also gitignored, so they never reach the public repo either).
  eleventyConfig.ignores.add("src/uncviet/placement/*.md");
  eleventyConfig.ignores.add("src/uncviet/viet101/DRAFT-*.md");

  // ── Filters ─────────────────────────────────────────────────────
  eleventyConfig.addFilter("slug", (str) =>
    (str || "").toLowerCase().replace(/\s+/g, "-").replace(/[^\w-]/g, "")
  );
  eleventyConfig.addFilter("truncate", (str, len = 60) =>
    str && str.length > len ? str.slice(0, len) + "…" : str
  );

  // ── Section tag: inject active section into data ─────────────────
  // Each section folder has a directory data file (e.g. taskbook/taskbook.json)
  // that sets { section: "taskbook" } — picked up automatically by Eleventy.

  return {
    dir: {
      input:    "src",
      output:   "_site",
      includes: "_includes",
      data:     "_data",
    },
    templateFormats:      ["njk", "md", "html"],
    markdownTemplateEngine: "njk",
    htmlTemplateEngine:   "njk",
  };
};
