/* 🔁 review: today's due words; easy question for young cards, typing once a word is settling in */
function reviewMode(set) {
  const order = shuffle(set.cards).slice(0, 30), missed = new Set(), total = order.length;
  let queue = [...order], doneN = 0;
  function next() {
    if (!queue.length) {
      const left = ALL.filter(c => isDue(c.i)).length;
      return summary({ big: '✅', title: 'Ôn xong! · Review done', text: total + ' từ · ' + (total - missed.size) + ' nhớ ngay · remembered first time.' + (left ? ' Còn ' + left + ' từ cần ôn · ' + left + ' more due.' : ' Hẹn bạn ngày mai! · See you tomorrow.'),
        missed: order.filter(c => missed.has(c.i)), acts: (left ? '<button type="button" class="btn pri" data-a="moreRev">Ôn thêm · Review more</button>' : '') + '<a class="btn" href="#/">Trang chủ · Home</a>' });
    }
    const c = queue.shift(), b = (S.srs[c.i] || {}).b || 0;
    const kind = missed.has(c.i) ? 'mc-vn' : b >= 3 ? (Math.random() < 0.5 ? 'type-en' : 'type-audio') : ['mc-vn', 'mc-en', 'mc-audio'][Math.floor(Math.random() * 3)];
    ask($('#stage'), { kind, card: c }, ALL, ok => {
      grade(c.i, ok);
      if (ok) doneN++; else { missed.add(c.i); queue.splice(Math.min(3, queue.length), 0, c); }
      next();
    }, progHtml(doneN, total, doneN + ' / ' + total + ' từ', missed.size ? '✗ ' + missed.size : ''));
  }
  A.moreRev = () => route();
  next();
}

/* 🧩 match: 6 pairs against the clock */
function matchMode(set) {
  const best = S.best[set.key];
  stage('<div class="empty"><b>🧩 Ghép từ · Match</b>Ghép 6 cặp từ tiếng Việt với nghĩa tiếng Anh nhanh nhất có thể. Match 6 Vietnamese words to their meanings as fast as you can — a wrong pair adds 1 second.' +
    (best ? '<br>Kỷ lục · Best: <b style="display:inline">' + best.toFixed(1) + ' s</b>' : '') + '<br><button type="button" class="btn pri" data-a="mStart">Bắt đầu · Start</button></div>');
  let timer = 0;
  A.mStart = () => {
    const pairs = [], seenE = new Set();
    for (const c of shuffle(set.cards)) { if (pairs.length >= 6) break; if (!seenE.has(c.e)) { seenE.add(c.e); pairs.push(c); } }
    const tiles = shuffle([...pairs.map(c => ({ c, vn: true })), ...pairs.map(c => ({ c, vn: false }))]);
    let sel = null, left = pairs.length, pen = 0; const t0 = Date.now();
    stage('<div class="toolbar"><span class="grow"><b>Ghép · Match</b> — chọn một từ rồi chọn nghĩa của nó · pick a word, then its meaning</span><span class="timer" id="tm">0.0 s</span></div><div class="mgrid" id="mg">' +
      tiles.map((t, k) => '<button type="button" class="tile' + (t.vn ? ' vn' : '') + '" data-k="' + k + '"' + (t.vn ? ' lang="vi"' : '') + '>' + esc(t.vn ? t.c.v : t.c.e) + '</button>').join('') + '</div>');
    const tm = $('#tm'); timer = setInterval(() => { tm.textContent = ((Date.now() - t0) / 1000 + pen).toFixed(1) + ' s'; }, 100);
    $('#mg').addEventListener('click', e => {
      const b = e.target.closest('.tile'); if (!b || b.classList.contains('gone')) return;
      const t = tiles[+b.dataset.k];
      if (t.vn) say(t.c);
      if (!sel) { sel = b; b.classList.add('sel'); return; }
      if (sel === b) { b.classList.remove('sel'); sel = null; return; }
      const s = tiles[+sel.dataset.k];
      if (s.vn === t.vn) { sel.classList.remove('sel'); sel = b; b.classList.add('sel'); return; }
      if (s.c.i === t.c.i) {
        sel.classList.add('gone'); b.classList.add('gone'); sel = null;
        if (--left === 0) {
          clearInterval(timer);
          const secs = (Date.now() - t0) / 1000 + pen, rec = !S.best[set.key] || secs < S.best[set.key];
          if (rec) { S.best[set.key] = secs; save(); }
          summary({ big: secs.toFixed(1) + ' s', title: rec ? '🏆 Kỷ lục mới! · New best!' : 'Xong! · Done', text: 'Kỷ lục · Best: ' + S.best[set.key].toFixed(1) + ' s' + (pen ? ' · phạt · penalty +' + pen + ' s' : ''),
            missed: [], acts: '<button type="button" class="btn pri" data-a="mStart">Chơi lại · Play again</button>' });
        }
      } else {
        pen++; const a = sel; sel = null;
        [a, b].forEach(x => { x.classList.remove('sel'); x.classList.add('bad'); setTimeout(() => x.classList.remove('bad'), 400); });
      }
    });
  };
  cleanup = () => clearInterval(timer);
}

/* 📝 test: a mixed quiz, scored at the end */
function testMode(set) {
  const TYPES = [['mc-vn', 'Việt → chọn nghĩa'], ['mc-en', 'Anh → chọn từ'], ['mc-audio', '🎧 Nghe → chọn nghĩa'], ['type-en', '✍️ Anh → viết tiếng Việt'], ['type-audio', '🎧 Chính tả · dictation']];
  const n = set.cards.length, sizes = [10, 20, 30].filter(x => x < n).concat([n]);
  stage('<div class="setup"><h2>📝 Kiểm tra · Test yourself</h2><p>Câu hỏi trộn nhiều dạng; điểm ở cuối bài. Mixed questions, scored at the end — try it before a quiz or exam.</p>' +
    '<fieldset><legend>Số câu · Questions</legend><div class="chips">' + sizes.map((s, k) => '<label><input type="radio" name="tn" value="' + s + '"' + (k === Math.min(1, sizes.length - 1) ? ' checked' : '') + '>' + (s === n ? 'Tất cả · all ' + n : s) + '</label>').join('') + '</div></fieldset>' +
    '<fieldset><legend>Dạng câu hỏi · Question types</legend><div class="chips">' + TYPES.map(([k, t]) => '<label><input type="checkbox" name="tt" value="' + k + '" checked>' + t + '</label>').join('') + '</div></fieldset>' +
    '<p style="margin-top:1.2rem"><button type="button" class="btn pri" data-a="tStart">Bắt đầu · Start →</button></p></div>');
  A.tStart = () => {
    const size = +document.querySelector('[name=tn]:checked').value, kinds = [...document.querySelectorAll('[name=tt]:checked')].map(x => x.value);
    if (!kinds.length) return chip('Chọn ít nhất một dạng · pick at least one type');
    const items = shuffle(set.cards).slice(0, size).map((c, k) => ({ card: c, kind: kinds[k % kinds.length] }));
    shuffle(items.map(x => x.kind)).forEach((k, j) => { items[j].kind = k; });
    let k = 0, right = 0; const missed = [];
    const next = () => {
      if (k >= items.length) {
        const pct = Math.round(right / items.length * 100);
        return summary({ big: pct + '%', title: pct >= 90 ? 'Xuất sắc! · Excellent' : pct >= 75 ? 'Tốt lắm! · Well done' : pct >= 50 ? 'Khá rồi · Getting there' : 'Cố lên! · Keep going',
          text: right + ' / ' + items.length + ' câu đúng · correct.', missed, acts: missBtn(missed) + '<button type="button" class="btn" data-a="tAgain">Kiểm tra lại · New test</button>' });
      }
      const it = items[k];
      ask($('#stage'), it, set.cards, ok => { grade(it.card.i, ok); if (ok) right++; else missed.push(it.card); k++; next(); },
        progHtml(k, items.length, 'Câu · Question ' + (k + 1) + ' / ' + items.length, '✓ ' + right));
    };
    next();
  };
  A.tAgain = () => testMode(set);
}

