/* ───────── Vietnamese text: one tone-mark placement, so hòa = hoà and khỏe = khoẻ when answers are checked ───────── */
const TM = ['́', '̀', '̉', '̃', '̣'];   // sắc huyền hỏi ngã nặng → tone 1…5
const VOW = 'aăâeêioôơuưy', HAT = 'ăâêôơư';
function split(w) {   // NFC word → { ch: letters without tone, tone }
  let tone = 0; const ch = [];
  for (const c of w) { let keep = ''; for (const m of c.normalize('NFD')) { const k = TM.indexOf(m); if (k >= 0) tone = k + 1; else keep += m; } ch.push(keep.normalize('NFC')); }
  return { ch, tone };
}
function tonePos(ch) {
  const lc = k => (ch[k] || '').toLowerCase(), isV = k => k < ch.length && VOW.includes(lc(k));
  const P = [];
  for (let k = 0; k < ch.length; k++) {
    if (!isV(k)) { if (P.length) break; continue; }
    if (!P.length && ((lc(k) === 'u' && lc(k - 1) === 'q') || (lc(k) === 'i' && lc(k - 1) === 'g' && k === 1 && isV(k + 1)))) continue;   // qu-, gi- + vowel
    P.push(k);
  }
  if (!P.length) return -1;
  const hats = P.filter(k => HAT.includes(lc(k)));
  if (hats.length) return hats[hats.length - 1];
  if (P.length === 1) return P[0];
  if (P.length >= 3) return P[1];
  return P[1] < ch.length - 1 ? P[1] : P[0];   // closed (toán) → 2nd vowel; open (hòa, khỏe, mùa) → 1st
}
function join(ch, tone) {
  const out = [...ch], k = tonePos(out);
  if (tone && k >= 0) out[k] = (out[k].normalize('NFD') + TM[tone - 1]).normalize('NFC');
  return out.join('');
}
const canon = s => String(s).normalize('NFC').toLowerCase().replace(/\p{L}+/gu, w => { const x = split(w); return join(x.ch, x.tone); });
const PUNCT = /[.,!?;:…"“”'‘’()«»\-–—]/g;
const norm = s => canon(s).replace(PUNCT, ' ').replace(/\s+/g, ' ').trim();
const bareOf = s => s.normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/đ/g, 'd');
const altsOf = v => [...new Set([v, ...v.split(/\s*\/\s*/)])];
const escRe = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
function fits(input, alt, bare) {   // "…" in an answer is a gap: "không … mấy" accepts "không mấy" and "không đẹp mấy"
  const f = bare ? s => bareOf(norm(s)) : norm, n = f(input);
  if (!alt.includes('…')) return n === f(alt);
  return new RegExp('^' + alt.split('…').map(p => escRe(f(p))).join('.*?') + '$').test(n);
}
function check(input, card, pool) {
  if (!norm(input)) return 'empty';
  if (altsOf(card.v).some(a => fits(input, a))) return 'ok';
  if (pool.some(c => c.i !== card.i && c.e === card.e && altsOf(c.v).some(a => fits(input, a)))) return 'ok';   // same English, other word
  if (altsOf(card.v).some(a => fits(input, a, true))) return 'near';   // right letters, wrong tone / vowel marks
  return 'no';
}
function markDiff(input, card) {   // the answer with the syllables the student got wrong highlighted
  const alt = altsOf(card.v).find(a => fits(input, a, true)) || card.v, mine = norm(input).split(' ');
  return norm(alt).split(' ').map((s, k) => s === mine[k] ? esc(s) : '<mark>' + esc(s) + '</mark>').join(' ');
}
function hintOf(card, level) {   // 1: first letters · 2: letters without tone marks
  const w = card.v.split(/\s*\/\s*/)[0];
  return level >= 2 ? bareOf(w.normalize('NFC')).replace(/Đ/g, 'D') : w.replace(/\p{L}+/gu, m => m[0] + '_'.repeat(m.length - 1));
}

/* ───────── Telex typing, for computers without a Vietnamese keyboard ───────── */
function telex(word, key) {   // the word before the caret + the key typed → the new word, or null to type the key as is
  const k = key.toLowerCase(), { ch, tone } = split(word.normalize('NFC'));
  const lo = i => ch[i].toLowerCase(), put = (i, c) => { ch[i] = ch[i] === ch[i].toLowerCase() ? c : c.toUpperCase(); };
  const T = 'sfrxj'.indexOf(k);
  if (T >= 0) { if (tonePos(ch) < 0) return null; return T + 1 === tone ? join(ch, 0) + key : join(ch, T + 1); }   // same tone twice = undo
  if (k === 'z') return tone ? join(ch, 0) : null;
  if ('aeo'.includes(k)) {
    const fam = { a: 'aăâ', e: 'eê', o: 'oôơ' }[k], hat = { a: 'â', e: 'ê', o: 'ô' }[k];
    for (let i = ch.length - 1; i >= 0; i--) if (fam.includes(lo(i))) {
      if (lo(i) === hat) { put(i, k); return join(ch, tone) + key; }
      put(i, hat); return join(ch, tone);
    }
    return null;
  }
  if (k === 'w') {
    for (let i = ch.length - 2; i >= 0; i--) if ('uư'.includes(lo(i)) && 'oơ'.includes(lo(i + 1))) {   // uo → ươ
      if (lo(i) === 'ư' && lo(i + 1) === 'ơ') { put(i, 'u'); put(i + 1, 'o'); return join(ch, tone) + key; }
      put(i, 'ư'); put(i + 1, 'ơ'); return join(ch, tone);
    }
    for (let i = ch.length - 1; i >= 0; i--) {
      const m = { a: 'ă', 'â': 'ă', o: 'ơ', 'ô': 'ơ', u: 'ư' }[lo(i)];
      if (m) { put(i, m); return join(ch, tone); }
      const back = { 'ă': 'a', 'ơ': 'o', 'ư': 'u' }[lo(i)];
      if (back) { put(i, back); return join(ch, tone) + key; }
    }
    return join(ch, tone) + (key === 'W' ? 'Ư' : 'ư');
  }
  if (k === 'd' && ch.length) {
    if (lo(0) === 'd') { put(0, 'đ'); return join(ch, tone); }
    if (lo(0) === 'đ') { put(0, 'd'); return join(ch, tone) + key; }
  }
  return null;
}
function telexOn(inp) {
  inp.addEventListener('beforeinput', e => {
    if (!S.telex || e.inputType !== 'insertText' || !e.data || e.data.length !== 1 || e.isComposing) return;
    const p = inp.selectionStart; if (p !== inp.selectionEnd) return;
    const word = /\p{L}*$/u.exec(inp.value.slice(0, p))[0];
    if (!word && e.data.toLowerCase() !== 'w') return;
    const out = telex(word, e.data); if (out == null) return;
    e.preventDefault(); inp.setRangeText(out, p - word.length, p, 'end');
    inp.dispatchEvent(new Event('input', { bubbles: true }));
  });
}

