/* 🧠 learn: rounds of 7 — each word first as multiple choice, then typed; a miss comes back a little later */
function learnMode(set) {
  const notYet = set.cards.filter(c => status(c.i) !== 'mastered');
  const pool = shuffle(notYet.length ? notYet : set.cards), stageOf = {}, missed = new Set();
  const ROUND = 7, rounds = Math.ceil(pool.length / ROUND);
  let rn = 0, queue = [], roundCards = [];
  const doneSteps = () => pool.reduce((s, c) => s + (stageOf[c.i] || 0), 0);
  function startRound() {
    roundCards = pool.slice(rn * ROUND, rn * ROUND + ROUND); queue = [...roundCards];
    roundCards.forEach(c => { stageOf[c.i] = 0; }); next();
  }
  function next() {
    if (!queue.length) return roundDone();
    const c = queue.shift(), st = stageOf[c.i];
    const kind = st === 0 ? (Math.random() < 0.5 ? 'mc-vn' : 'mc-en') : 'type-en';
    const head = progHtml(doneSteps(), pool.length * 2, 'Vòng · Round ' + (rn + 1) + ' / ' + rounds, (notYet.length ? '' : 'ôn lại từ đã thuộc · all mastered — revising ') + pool.length + ' từ');
    ask($('#stage'), { kind, card: c }, set.cards, ok => {
      if (ok) { stageOf[c.i] = st + 1; if (st === 0) queue.push(c); else grade(c.i, true); }
      else { missed.add(c.i); grade(c.i, false); queue.splice(Math.min(2, queue.length), 0, c); }
      next();
    }, head);
  }
  function roundDone() {
    rn++;
    const last = rn >= rounds, miss = roundCards.filter(c => missed.has(c.i));
    summary({ big: last ? '🎉' : '✓ ' + rn + ' / ' + rounds, title: last ? 'Xong! Bạn đã học hết bộ này · All done' : 'Xong vòng ' + rn + ' · Round ' + rn + ' done',
      text: roundCards.length + ' từ · ' + (roundCards.length - miss.length) + ' đúng ngay lần đầu · right first time. ' + (last ? 'Các từ này sẽ quay lại trong 🔁 Ôn hôm nay · These words will come back in your daily review.' : ''),
      missed: miss,
      acts: last ? missBtn(pool.filter(c => missed.has(c.i))) + '<a class="btn" href="#/set/' + set.key + '/listen">🎧 Sang Nghe · Listen →</a><a class="btn" href="#/set/' + set.key + '/test">📝 Kiểm tra · Test</a>'
        : '<button type="button" class="btn pri" data-a="nextRound">Vòng tiếp · Next round →</button>' });
    if (!last) keyFn = e => { if (e.key === 'Enter') A.nextRound(); };
  }
  A.nextRound = () => startRound();
  startRound();
}

/* one pass over the set with a single question kind; misses return once at the end */
function drill(set, kindFn, sub) {
  const order = shuffle(set.cards), missed = [];
  let first = 0, tried = 0, queue = [...order];
  const retry = new Set();
  function next() {
    if (!queue.length) return summary({ big: Math.round(first / order.length * 100) + '%', title: 'Xong! · Done', text: first + ' / ' + order.length + ' đúng ngay lần đầu · right first time.', missed,
      acts: missBtn(missed) + '<button type="button" class="btn" data-a="redo">Làm lại · Again</button>' });
    const c = queue.shift();
    ask($('#stage'), { kind: kindFn(c), card: c }, set.cards, ok => {
      if (!retry.has(c.i)) { tried++; if (ok) first++; else { missed.push(c); retry.add(c.i); queue.push(c); } }
      grade(c.i, ok);
      next();
    }, (sub || '') + progHtml(tried, order.length, (retry.has(c.i) ? 'Làm lại · retry' : (tried + 1) + ' / ' + order.length), '✓ ' + first));
  }
  A.redo = () => drill(set, kindFn, sub);
  next();
}
